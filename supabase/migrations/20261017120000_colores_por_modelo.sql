/* Colores por modelo, definidos por la tienda: al elegir el modelo en "Ingresar equipo" solo
   aparecen sus colores. Si un modelo no está acá, se usan los del catálogo Apple.
   Aplicada a mano desde el editor SQL (Lovable Cloud). */
create table if not exists public.colores_modelo (
  id uuid primary key default gen_random_uuid(),
  modelo text not null,
  color text not null,
  orden int not null default 0,
  created_at timestamptz not null default now()
);
create unique index if not exists colores_modelo_unico on public.colores_modelo (lower(modelo), lower(color));
alter table public.colores_modelo enable row level security;
grant select on public.colores_modelo to authenticated;
grant insert, update, delete on public.colores_modelo to authenticated;
drop policy if exists "colores_modelo lectura" on public.colores_modelo;
create policy "colores_modelo lectura" on public.colores_modelo for select to authenticated
  using (public.mi_rol() is not null);
drop policy if exists "colores_modelo edicion" on public.colores_modelo;
create policy "colores_modelo edicion" on public.colores_modelo for all to authenticated
  using (public.mi_rol() in ('direccion', 'administracion'))
  with check (public.mi_rol() in ('direccion', 'administracion'));

